/**
 * E2E — US-02: Inline Agent Registration in Wizard
 *
 * Definition-of-Done:
 *   "E2E test: full wizard flow — signup → agent registration → agent appears in Agents list"
 *   "Manual test: 'Skip for now' warning renders; skipping and proceeding fails at US-05
 *    live indicator as expected"
 *
 * Mocks the provision + agent register APIs to keep the test hermetic (no live DB required).
 */

import { test, expect } from '@playwright/test';

// ─── Shared mock data ─────────────────────────────────────────────────────────

const MOCK_TENANT_ID   = 'org_e2e_wizard_001';
const MOCK_USER_ID     = 'usr_e2e_wizard_001';
const MOCK_API_KEY     = 'ask_abcdefgh_ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqr';
const MOCK_FINGERPRINT = 'sha256:' + 'a'.repeat(64);
const MOCK_AGENT_ID    = 'agt_e2e_wizard_001';
const MOCK_AGENT_NAME  = 'My Test Agent';

// ─── Fixtures: mock API responses ─────────────────────────────────────────────

async function mockWizardApis(page: import('@playwright/test').Page) {
    // POST /api/v1/tenants/provision
    await page.route('**/api/v1/tenants/provision', (route) =>
        route.fulfill({
            status: 201,
            contentType: 'application/json',
            body: JSON.stringify({
                tenant_id:      MOCK_TENANT_ID,
                user_id:        MOCK_USER_ID,
                org_name:       'E2E Test Corp',
                org_slug:       'e2e-test-corp',
                sdk_api_key:    MOCK_API_KEY,
                sdk_api_key_id: 'key_e2e_001',
                key_fingerprint: MOCK_FINGERPRINT,
                message:        'Tenant provisioned.',
            }),
        })
    );

    // POST /api/v1/agents/register
    await page.route('**/api/v1/agents/register', (route) =>
        route.fulfill({
            status: 200,
            contentType: 'application/json',
            body: JSON.stringify({ agent_id: MOCK_AGENT_ID, name: MOCK_AGENT_NAME }),
        })
    );

    // POST /api/v1/auth/login (auto-login after provision)
    await page.route('**/api/v1/auth/**', (route) =>
        route.fulfill({
            status: 200,
            contentType: 'application/json',
            body: JSON.stringify({ token: 'mock-session-token', user_id: MOCK_USER_ID }),
        })
    );

    // GET /api/v1/onboarding/status
    await page.route('**/api/v1/onboarding/status**', (route) =>
        route.fulfill({
            status: 200,
            contentType: 'application/json',
            body: JSON.stringify({ first_call_received: false, last_decision: null }),
        })
    );

    // Silence EIAA runtime keys
    await page.route('**/api/eiaa/v1/runtime/keys', (route) =>
        route.fulfill({ status: 200, contentType: 'application/json', body: '[]' })
    );
}

// ─── Tests ────────────────────────────────────────────────────────────────────

test.describe('US-02 — Inline Agent Registration in Wizard', () => {

    test.beforeEach(async ({ page }) => {
        // Persist runtime-keys mock across all navigations in the test.
        await page.route('**/api/eiaa/v1/runtime/keys', (route) =>
            route.fulfill({ status: 200, contentType: 'application/json', body: '[]' })
        );
        await mockWizardApis(page);
    });

    /**
     * Full wizard: org step → admin step → agent step → key step → live step.
     * After completing agent registration the agent must appear in the Agents list.
     */
    test('full wizard flow: signup → agent registration → wizard completion', async ({ page }) => {
        await page.goto('/sign-up');

        // ── Step 1: Org name + slug ─────────────────────────────────────────
        // Placeholder is "Acme Corp" — match any text input on the page (first one).
        const orgInput = page.locator('input[type="text"]').first();
        await expect(orgInput).toBeVisible({ timeout: 5_000 });
        await orgInput.fill('E2E Test Corp');
        // Slug is auto-generated by onChange — wait for the Continue button to become enabled.
        const nextBtn = page.locator('button:has-text("Continue"), button:has-text("Next")').first();
        await expect(nextBtn).toBeEnabled({ timeout: 5_000 });
        await nextBtn.click();

        // ── Step 2: Admin account ───────────────────────────────────────────
        // Fill optional first/last name so the provision payload is complete.
        const firstNameInput = page.locator('input[type="text"]').nth(0);
        if (await firstNameInput.isVisible({ timeout: 2_000 })) await firstNameInput.fill('Test');
        const lastNameInput = page.locator('input[type="text"]').nth(1);
        if (await lastNameInput.isVisible({ timeout: 2_000 })) await lastNameInput.fill('User');
        const emailInput = page.locator('input[type="email"]').first();
        await expect(emailInput).toBeVisible({ timeout: 5_000 });
        await emailInput.fill(`wizard-${Date.now()}@example.com`);
        const pwInput = page.locator('input[type="password"]').first();
        await expect(pwInput).toBeVisible({ timeout: 3_000 });
        await pwInput.fill('SecureTest@123!');
        // Wait for "Create workspace" button to be enabled (email + password both filled).
        const createBtn = page.locator('button:has-text("Create workspace")').first();
        await expect(createBtn).toBeEnabled({ timeout: 5_000 });
        await createBtn.click();

        // ── Step 3: Agent registration ──────────────────────────────────────
        // Wait for the agent step heading
        await expect(page.locator('h2:has-text("Register your first agent")')).toBeVisible({ timeout: 10_000 });

        // Agent name: first text input on the agent step (value defaults to 'my-first-agent').
        // We fill it to exercise the onDone(agentName) path.
        const agentNameInput = page.locator('input[type="text"]').first();
        await expect(agentNameInput).toBeVisible({ timeout: 5_000 });
        await agentNameInput.fill(MOCK_AGENT_NAME);

        // Submit agent registration — button is enabled by default (web_search pre-selected).
        const registerBtn = page.locator('button:has-text("Register agent")').first();
        await expect(registerBtn).toBeEnabled({ timeout: 5_000 });
        await registerBtn.click();

        // Wizard advances — agent_id is stored in state (not URL, not localStorage)
        // We verify by checking the wizard progressed past the agent step
        // ── Step 4: API key display ─────────────────────────────────────────
        // Key step heading: "Save your SDK key"
        await expect(page.locator('h2:has-text("Save your SDK key")')).toBeVisible({ timeout: 10_000 });
        // Tick "I've saved my key" checkbox to enable the Continue → button
        const savedCheckbox = page.locator('input[type="checkbox"]').last();
        await expect(savedCheckbox).toBeVisible({ timeout: 5_000 });
        await savedCheckbox.check();
        // Now Continue is enabled
        const keyContBtn = page.locator('button:has-text("Continue")').first();
        await expect(keyContBtn).toBeEnabled({ timeout: 3_000 });
        await keyContBtn.click();

        // ── Step 5: Live indicator ──────────────────────────────────────────
        // Mock onboarding status returns {first_call_received: false} so we see
        // the "waiting for your first call" state.
        const waitingIndicator = page.locator('text=/waiting for your first call/i');
        await expect(waitingIndicator).toBeVisible({ timeout: 10_000 });

        // "Go to dashboard" button always available
        const dashBtn = page.locator('button:has-text("Go to dashboard")');
        await expect(dashBtn).toBeVisible();
    });

    /**
     * "Skip for now" shows a warning that the first authorize() call will fail.
     */
    test('skip agent registration shows warning', async ({ page }) => {
        await page.goto('/sign-up');

        // ── Step 1: Org ─────────────────────────────────────────────────────
        const orgInput = page.locator('input[type="text"]').first();
        await expect(orgInput).toBeVisible({ timeout: 5_000 });
        await orgInput.fill('Skip Test Corp');
        const nextBtn = page.locator('button:has-text("Continue"), button:has-text("Next")').first();
        await expect(nextBtn).toBeEnabled({ timeout: 5_000 });
        await nextBtn.click();

        // ── Step 2: Admin account ───────────────────────────────────────────
        const emailInput = page.locator('input[type="email"]').first();
        if (await emailInput.isVisible({ timeout: 5_000 })) {
            await emailInput.fill(`skip-${Date.now()}@example.com`);
            const pwInput = page.locator('input[type="password"]').first();
            if (await pwInput.isVisible({ timeout: 2_000 })) await pwInput.fill('SecureTest@123!');
            const createBtn = page.locator('button:has-text("Create workspace")').first();
            await expect(createBtn).toBeEnabled({ timeout: 5_000 });
            await createBtn.click();
        }

        // Look for "Skip — I'm only using human authentication" button
        const skipLink = page.locator('button:has-text("Skip")');
        await expect(skipLink).toBeVisible({ timeout: 8_000 });
        await skipLink.click();

        // After skipping, the wizard advances to the key step where the warning
        // is rendered persistently (agentSkipped=true).
        await expect(page.locator('h2:has-text("Save your SDK key")')).toBeVisible({ timeout: 8_000 });
        const warning = page.locator('p').filter({ hasText: /will fail without a registered agent/i });
        await expect(warning).toBeVisible({ timeout: 5_000 });
    });

    /**
     * US-05 DoD: after skipping agent registration, the live indicator's
     * polling reflects no first call (wizard still works, just no success state).
     */
    test('skipping agent registration does not break live indicator', async ({ page }) => {
        await page.goto('/sign-up');

        // ── Step 1: Org ─────────────────────────────────────────────────────
        const orgInput = page.locator('input[type="text"]').first();
        await expect(orgInput).toBeVisible({ timeout: 5_000 });
        await orgInput.fill('No Agent Corp');
        const n = page.locator('button:has-text("Continue"), button:has-text("Next")').first();
        await expect(n).toBeEnabled({ timeout: 5_000 });
        await n.click();

        // ── Step 2: Admin account ───────────────────────────────────────────
        const emailInput = page.locator('input[type="email"]').first();
        if (await emailInput.isVisible({ timeout: 5_000 })) {
            await emailInput.fill(`noagent-${Date.now()}@example.com`);
            const pw = page.locator('input[type="password"]').first();
            if (await pw.isVisible({ timeout: 2_000 })) await pw.fill('SecureTest@123!');
            const cb = page.locator('button:has-text("Create workspace")').first();
            await expect(cb).toBeEnabled({ timeout: 5_000 });
            await cb.click();
        }

        // Skip agent step
        const skipLink = page.locator('button:has-text("Skip")');
        await expect(skipLink).toBeVisible({ timeout: 8_000 });
        await skipLink.click();

        // After skipping → key step. Tick the checkbox then advance.
        await expect(page.locator('h2:has-text("Save your SDK key")')).toBeVisible({ timeout: 8_000 });
        const savedCb = page.locator('input[type="checkbox"]').last();
        await expect(savedCb).toBeVisible({ timeout: 3_000 });
        await savedCb.check();
        const keyBtn = page.locator('button:has-text("Continue")').first();
        await expect(keyBtn).toBeEnabled({ timeout: 3_000 });
        await keyBtn.click();

        // Live indicator must still render (waiting state — not crashed)
        const indicator = page.locator('text=/waiting for your first call/i');
        await expect(indicator).toBeVisible({ timeout: 10_000 });
        await expect(page.locator('button:has-text("Go to dashboard")')).toBeVisible();
    });
});
